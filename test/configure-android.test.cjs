'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const { patchRegistration, configurePaths } = require('../scripts/configure-android.cjs');
const hook = require('../hooks/after-prepare.cjs');
const parent = 'com.randdusing.bluetoothle.BluetoothLePlugin';
const native = 'com.hme.bluetoothle.background.BLEBackgroundPlugin';
const xml = '<widget><feature name="Other"><param name="android-package" value="Other"/></feature><feature name="BluetoothLePlugin"><param name="android-package" value="' + parent + '"/></feature></widget>';
test('Android registration changes only public entry class, idempotently and reversibly', () => {
    const changed = patchRegistration(xml);
    assert.equal(changed, xml.replace(parent, native));
    assert.equal(patchRegistration(changed), changed);
    assert.equal(patchRegistration(changed, true), xml);
    assert.equal(patchRegistration(xml.replaceAll('"', "'")), changed.replaceAll('"', "'"));
    const comment = '<!-- <feature name="BluetoothLePlugin"><param name="android-package" value="Other"/></feature> -->';
    assert.equal(patchRegistration(comment + xml), comment + changed);
    assert.throws(() => patchRegistration(xml + xml), /exactly one/);
    assert.throws(() => patchRegistration(xml.replace(parent, 'CustomOwner')), /another native class/);
    assert.throws(() => patchRegistration(xml.replace('android-package" value="' + parent, 'ios-package" value="' + parent)), /android-package/);
});
test('Android installer pins parent, preserves sources, and supports Cordova prepare and Capacitor CLI', t => {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 'ble-background-android-setup-'));
    t.after(() => fs.rmSync(root, { recursive: true, force: true }));
    const parentDirectory = path.join(root, 'node_modules/cordova-plugin-bluetoothle');
    fs.mkdirSync(parentDirectory, { recursive: true });
    const metadata = path.join(parentDirectory, 'package.json');
    fs.writeFileSync(metadata, '{"version":"6.7.4"}');
    const source = path.join(parentDirectory, 'BluetoothLePlugin.java'); fs.writeFileSync(source, 'unchanged');
    const config = path.join(root, 'platforms/android/app/src/main/res/xml/config.xml');
    fs.mkdirSync(path.dirname(config), { recursive: true }); fs.writeFileSync(config, xml);
    hook({ opts: { platforms: ['android'], projectRoot: root } });
    assert.equal(fs.readFileSync(config, 'utf8'), patchRegistration(xml));
    assert.equal(fs.readFileSync(source, 'utf8'), 'unchanged');
    configurePaths({ root, config, restore: true }); assert.equal(fs.readFileSync(config, 'utf8'), xml);
    const script = path.resolve(__dirname, '../scripts/configure-android.cjs');
    const result = spawnSync(process.execPath, [script, '--root', root, '--config', config], { encoding: 'utf8' });
    assert.equal(result.status, 0, result.stderr);
    const skip = spawnSync(process.execPath, [script, '--root', '/missing'], { env: { ...process.env, CAPACITOR_PLATFORM_NAME: 'ios' } });
    assert.equal(skip.status, 0);
    fs.writeFileSync(metadata, '{"version":"7.0.0"}');
    assert.throws(() => configurePaths({ root, config }), /requires.*6.7.4/);
});
